"""Outside-in tests for scripts/reviewer/ai_pr_reviewer.js, against a fake
Gitea and fake OpenAI-compatible providers on localhost.

Contract: configuration comes only from the environment. The reviewer fetches
the PR diff, refuses to send a diff with secret-like content to any provider
(posting REQUEST_CHANGES instead), otherwise asks the configured providers in
order (mammouth, Groq, Ollama; Gemini is skipped here because its endpoint is
fixed) and posts one review with a machine-readable marker. Exit 0 on success
or an empty diff; exit 1 with the reason on stderr otherwise.

Secret-shaped strings are assembled at run time so this file does not itself
trip the reviewer's or any other secret scanner.
"""

import json
import re
import unittest

from support import FakeServer, HelperTestCase, base_env, run_tool

PRIVATE_KEY_LINE = "-----BEGIN " + "RSA PRIVATE" + " KEY-----"
DIFF = """diff --git a/src/app.js b/src/app.js
--- a/src/app.js
+++ b/src/app.js
@@ -1,2 +1,3 @@
 const one = 1;
-const two = 2;
+const total = one + 2;
+export { total };
"""
MARKER = re.compile(r"<!-- night-shift-review-task:v1 (\{.*\}) -->")


def chat_reply(content):
    return {"choices": [{"message": {"role": "assistant", "content": content}}]}


class FakeServices:
    def __init__(self):
        self.diff = (200, DIFF)
        self.review_reply = (201, {"id": 1})
        self.providers = {}

    def __call__(self, request):
        if request.method == "GET" and request.path == "/api/v1/repos/o/r/pulls/7.diff":
            return self.diff
        if request.method == "POST" and request.path == "/api/v1/repos/o/r/pulls/7/reviews":
            return self.review_reply
        for name, replies in self.providers.items():
            if request.method == "POST" and request.path == f"/{name}/v1/chat/completions":
                return replies.pop(0) if len(replies) > 1 else replies[0]
        return 404, {"message": "not found"}


class ReviewerTest(HelperTestCase):
    def setUp(self):
        super().setUp()
        self.services = FakeServices()
        self.server = FakeServer(self.services).__enter__()
        self.addCleanup(self.server.__exit__, None, None, None)
        self.style = self.tmp / "js-style.md"
        self.style.write_text("JS-STYLE-MARKER: prefer const\n")
        self.values = {"GITEA_TOKEN": "review-token", "GITEA_API_URL": self.server.url + "/api/v1/",
                       "GITEA_REPOSITORY": "o/r", "PR_NUMBER": "7", "HEAD_BRANCH": "feat/x",
                       "REVIEW_JS_STYLE_PATH": str(self.style), "REVIEW_TS_STYLE_PATH": str(self.tmp / "absent.md"),
                       "PROVIDER_RETRY_ATTEMPTS": "1"}

    def provider(self, name, *replies, key=None):
        self.services.providers[name] = list(replies)
        prefix = {"groq": "GROQ", "mammouth": "MAMMOUTH", "ollama": "OLLAMA"}[name]
        self.values[f"{prefix}_BASE_URL"] = f"{self.server.url}/{name}/v1"
        if key:
            self.values[f"{prefix}_API_KEY"] = key

    def review(self, **changes):
        values = dict(self.values)
        values.update(changes)
        values = {k: v for k, v in values.items() if v is not None}
        return run_tool("reviewer", [], env=base_env(self.home, values), cwd=self.tmp)

    def provider_requests(self, name=None):
        return [r for r in self.server.requests if r.path.endswith("/chat/completions")
                and (name is None or r.path.startswith(f"/{name}/"))]

    def posted(self):
        return self.server.matching("POST", "/pulls/7/reviews")

    def assert_review(self, verdict, event, review_text, findings=0, marker_extra=None):
        [post] = self.posted()
        payload = post.json()
        self.assertEqual(set(payload), {"body", "event"})
        self.assertEqual(payload["event"], event)
        body = payload["body"]
        match = MARKER.search(body)
        self.assertIsNotNone(match, body)
        marker = {"pr_number": 7, "verdict": verdict, "base_branch": "develop", "head_branch": "feat/x",
                  "validation_profile": "pr-review", "max_attempts": 3, "secret_findings_count": findings}
        marker.update(marker_extra or {})
        self.assertEqual(json.loads(match.group(1)), marker)
        expected = "\n".join(["### Automated Style Guide Review", "", f"Verdict: {verdict}", "", review_text, "",
                              match.group(0), "", "Review generated by self-hosted PR reviewer."])
        self.assertEqual(body, expected)
        self.assertEqual(post.headers["authorization"], "token review-token")
        self.assertEqual(post.headers["content-type"], "application/json")

    # Configuration

    def test_required_settings(self):
        cases = [({"GITEA_TOKEN": None}, "GITEA_TOKEN is not defined."),
                 ({"GITEA_API_URL": None}, "Set GITEA_API_URL and GITEA_REPOSITORY explicitly."),
                 ({"GITEA_REPOSITORY": None}, "Set GITEA_API_URL and GITEA_REPOSITORY explicitly."),
                 ({"PR_NUMBER": None}, "PR_NUMBER is missing or invalid."),
                 ({"PR_NUMBER": "0"}, "PR_NUMBER is missing or invalid."),
                 ({"PR_NUMBER": "seven"}, "PR_NUMBER is missing or invalid.")]
        for change, message in cases:
            with self.subTest(change=change):
                result = self.review(**change)
                self.assertEqual(result.returncode, 1)
                self.assertEqual(result.stderr.strip().splitlines()[-1], message)
        self.assertEqual(self.server.requests, [])

    def test_diff_is_fetched_with_the_token(self):
        self.provider("ollama", (200, chat_reply('{"verdict": "COMMENT", "review": "ok"}')))
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        diff_request = self.server.requests[0]
        self.assertEqual((diff_request.method, diff_request.path), ("GET", "/api/v1/repos/o/r/pulls/7.diff"))
        self.assertEqual(diff_request.headers["authorization"], "token review-token")

    def test_unfetchable_diff_is_never_reviewed(self):
        self.provider("ollama", (200, chat_reply('{"verdict": "APPROVE", "review": "ok"}')))
        self.services.diff = (404, {"message": "missing"})
        result = self.review()
        self.assertEqual(result.returncode, 1)
        self.assertIn("Cannot fetch the PR diff; refusing a local-checkout fallback.", result.stderr)
        self.assertEqual(self.provider_requests(), [])
        self.assertEqual(self.posted(), [])

    def test_empty_diff_posts_nothing(self):
        self.services.diff = (200, "  \n")
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("PR diff is empty; skipping review.", result.stdout)
        self.assertEqual(len(self.server.requests), 1)

    def test_no_provider_configured(self):
        result = self.review()
        self.assertEqual(result.returncode, 1)
        self.assertIn("No review provider configured", result.stderr)
        self.assertEqual(self.posted(), [])

    # Secret scanning

    def test_secret_in_added_line_blocks_without_calling_a_provider(self):
        self.provider("ollama", (200, chat_reply('{"verdict": "APPROVE", "review": "ok"}')))
        self.services.diff = (200, DIFF + "+" + PRIVATE_KEY_LINE + "\n")
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.provider_requests(), [])
        review_text = "\n".join([
            "Secret-like content was detected in the added diff before Gemini review.",
            "The diff was not sent to Gemini. Remove or rotate the suspected secret, then push again.",
            "",
            f"- private-key: `{PRIVATE_KEY_LINE}`"])
        self.assert_review("REQUEST_CHANGES", "REQUEST_CHANGES", review_text, findings=1)

    def test_high_entropy_token_is_a_secret(self):
        token = "gitea" + "_" + "q7Zp2LmX9vR4tB8nK3wY6cJ1"
        self.services.diff = (200, DIFF + f"+const auth = '{token}';\n")
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        body = self.posted()[0].json()["body"]
        self.assertIn("- github-or-gitea-token: `const auth = '" + token + "';`", body)

    def test_removed_lines_and_readable_identifiers_are_not_secrets(self):
        self.provider("ollama", (200, chat_reply('{"verdict": "COMMENT", "review": "Fine."}')))
        readable = "GITEA" + "_REVIEW_EVENT_BY_VERDICT"
        self.services.diff = (200, DIFF + "-" + PRIVATE_KEY_LINE + "\n+const name = " + readable + ";\n"
                              + "+const token" + " = 'aaaaaaaaaaaaaaaa';\n")
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(len(self.provider_requests()), 1)
        self.assert_review("COMMENT", "COMMENT", "Fine.")

    # Provider review

    def test_approve_is_posted_as_gitea_approved(self):
        self.provider("groq", (200, chat_reply('{"verdict": "APPROVE", "review": "Looks **good**."}')), key="groq-key")
        result = self.review(BASE_BRANCH="main", PR_REVIEW_LOOP_MAX_ATTEMPTS="5")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assert_review("APPROVE", "APPROVED", "Looks **good**.", marker_extra={"base_branch": "main", "max_attempts": 5})
        [request] = self.provider_requests("groq")
        self.assertEqual(request.headers["authorization"], "Bearer groq-key")
        payload = request.json()
        self.assertEqual(payload["model"], "llama-3.3-70b-versatile")
        self.assertEqual(payload["temperature"], 0.2)
        self.assertEqual(payload["response_format"], {"type": "json_object"})
        [message] = payload["messages"]
        self.assertEqual(message["role"], "user")
        self.assertIn("automated code reviewer for the o/r repository", message["content"])
        self.assertIn("JS-STYLE-MARKER: prefer const", message["content"])
        self.assertIn("```diff\n" + DIFF + "\n```", message["content"])

    def test_model_can_be_overridden(self):
        self.provider("groq", (200, chat_reply('{"verdict": "COMMENT", "review": "x"}')), key="k")
        self.review(GROQ_MODEL="custom-model")
        self.assertEqual(self.provider_requests("groq")[0].json()["model"], "custom-model")

    def test_request_changes_and_tolerant_parsing(self):
        replies = ['```json\n{"verdict": "REQUEST_CHANGES", "review": "Fix indentation."}\n```',
                   'Here you go: {"verdict": "REQUEST_CHANGES", "review": "Fix indentation."} Thanks!']
        for content in replies:
            with self.subTest(content=content):
                self.server.requests.clear()
                self.provider("ollama", (200, chat_reply(content)))
                result = self.review()
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assert_review("REQUEST_CHANGES", "REQUEST_CHANGES", "Fix indentation.")

    def test_provider_order_and_fallthrough(self):
        self.provider("mammouth", (400, {"error": "bad request"}), key="m-key")
        self.provider("groq", (200, chat_reply('{"verdict": "MERGE", "review": "x"}')), key="g-key")
        self.provider("ollama", (200, chat_reply('{"verdict": "COMMENT", "review": "From Ollama."}')))
        result = self.review()
        self.assertEqual(result.returncode, 0, result.stderr)
        order = [r.path.split("/")[1] for r in self.provider_requests()]
        self.assertEqual(order, ["mammouth", "groq", "ollama"])
        mammouth, _, ollama = self.provider_requests()
        self.assertNotIn("response_format", mammouth.json())
        self.assertEqual(mammouth.json()["model"], "claude-sonnet-4-6")
        self.assertNotIn("authorization", ollama.headers)
        self.assertEqual(ollama.json()["model"], "qwen2.5-coder:7b")
        self.assert_review("COMMENT", "COMMENT", "From Ollama.")

    def test_transient_provider_failure_is_retried(self):
        self.provider("ollama", (503, {"error": "loading"}), (200, chat_reply('{"verdict": "COMMENT", "review": "ok"}')))
        result = self.review(PROVIDER_RETRY_ATTEMPTS="2")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(len(self.provider_requests("ollama")), 2)
        self.assertEqual(len(self.posted()), 1)

    def test_caller_errors_are_not_retried(self):
        self.provider("ollama", (400, {"error": "bad"}), (200, chat_reply('{"verdict": "COMMENT", "review": "ok"}')))
        result = self.review(PROVIDER_RETRY_ATTEMPTS="3")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(len(self.provider_requests("ollama")), 1)

    def test_all_providers_failing_posts_nothing(self):
        self.provider("groq", (200, chat_reply('{"verdict": "APPROVE", "review": ""}')), key="k")
        self.provider("ollama", (200, chat_reply("not json at all")))
        result = self.review()
        self.assertEqual(result.returncode, 1)
        self.assertIn("All review providers failed. Last error:", result.stderr)
        self.assertEqual(self.posted(), [])

    def test_rejected_review_post_fails_loudly(self):
        self.provider("ollama", (200, chat_reply('{"verdict": "COMMENT", "review": "ok"}')))
        self.services.review_reply = (500, "server exploded")
        result = self.review()
        self.assertEqual(result.returncode, 1)
        self.assertIn("Gitea review submit returned HTTP 500: server exploded", result.stderr)


if __name__ == "__main__":
    unittest.main()
